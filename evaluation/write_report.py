"""Build eval_P4_TeamID.md from results/*.json (no numbers typed by hand).

    python -m evaluation.write_report
Metric order follows Problem Statement 4: RMSE, MAE, PSNR, SSIM, edge
preservation, boundary accuracy, (per upsampling factor), latency, memory.
"""
from __future__ import annotations

import json

from config import METHOD_LABELS, RESULTS_DIR, ROOT

USNS = "USN1,USN2,USN3,USN4"  # <-- replace with your team's USNs
OUT = ROOT / "eval_P4_TeamID.md"  # <-- rename to eval_P4_<YourTeamID>.md
ORDER = [("RMSE", "RMSE (m) ↓", 4), ("MAE", "MAE (m) ↓", 4), ("PSNR", "PSNR (dB) ↑", 2), ("SSIM", "SSIM ↑", 4),
         ("Edge F1", "Edge preservation F1 ↑", 4), ("Boundary RMSE", "Boundary RMSE (m) ↓", 4),
         ("Latency (s)", "Latency (s) ↓", 3), ("Peak mem (MB)", "Peak memory (MB) ↓", 1)]


def f(v, d):
    return "n/a" if v is None or v != v else f"{v:.{d}f}"


def main():
    B = json.loads((RESULTS_DIR / "benchmark.json").read_text())
    A = json.loads((RESULTS_DIR / "ablation.json").read_text())
    F = json.loads((RESULTS_DIR / "failure_analysis.json").read_text())
    ck = B["checkpoint"]
    L = [USNS, "", "# Evaluation — Problem Statement 4 (P4): Edge-Preserving Depth Map Upsampling and Refinement", "",
         "_Generated by `python -m evaluation.write_report` from `results/*.json`. Every number below was measured; "
         "nothing is typed by hand._", ""]
    L += ["## 1. Dataset details", "",
          "| Item | Value |", "|---|---|",
          "| Training data | " + ck.get("dataset", "?") + " |",
          f"| Test data | {B['n_scenes']} procedural RGB-D scenes, seeds {B['seeds'][0]}–{B['seeds'][-1]} "
          "(never used for training, validation or the demo samples) |",
          f"| Resolution | {B['size'][1]}×{B['size'][0]} ground truth; LR inputs {B['size'][1]//8}×{B['size'][0]//8} to {B['size'][1]//2}×{B['size'][0]//2} |",
          "| Scene content | tilted wall + floor, boxes, ellipsoids, polygons, thin poles/wires, stripes/checker/blob/noise textures, camouflaged objects, Lambertian shading |",
          "| Real datasets | NYU Depth V2, Middlebury and KITTI loaders/scripts are included (`training/prepare_nyu.py`, `training/evaluate.py`) but **were not run**: the build environment could not download them. Real-sensor accuracy is therefore not reported. |",
          ""]
    L += ["## 2. Experimental setup", "",
          f"* **Degradation (sensor model):** point-sampled ×{'/'.join(map(str, B['scales']))} downsampling, multiplicative Gaussian noise "
          f"σ = {B['degradation']['noise_std']} × depth, {B['degradation']['hole_fraction']*100:.0f} % blob-shaped holes.",
          f"* **Settings (identical for all methods):** `{B['settings']}`",
          f"* **DepthNet checkpoint:** {ck.get('parameters', 0):,} parameters, {ck.get('iterations')} iterations, batch {ck.get('batch_size')}, "
          f"{ck.get('crop')}² crops, {ck.get('train_minutes')} min on {ck.get('device')}; validation normalised RMSE "
          f"{ck.get('val_rmse_normalised', float('nan')):.4f} vs bicubic {ck.get('val_rmse_bicubic_normalised', float('nan')):.4f}.",
          "* **Metrics** (only on pixels valid in ground truth and prediction): RMSE, MAE; PSNR (peak = GT range); SSIM; "
          "Edge F1 between predicted and GT depth-discontinuity maps (2 px tolerance) = edge preservation; "
          "Boundary RMSE within 3 px of GT discontinuities = boundary accuracy; latency = wall-clock per image; "
          "memory = peak NumPy/Python allocation (tracemalloc).",
          "* **Hardware:** 2-core CPU, no GPU. Reproduce: `python -m evaluation.benchmark --n 20`.", ""]
    L += ["## 3. Comparative evaluation", ""]
    for s in B["scales"]:
        L += [f"### {s}× upsampling", "", "| Method | " + " | ".join(o[1] for o in ORDER) + " |",
              "|---|" + "---|" * len(ORDER)]
        rows = [r for r in B["rows"] if r["scale"] == s]
        best = {k: (max if "↑" in lab else min)(r[k] for r in rows) for k, lab, _ in ORDER}
        for r in rows:
            cells = []
            for k, _, d in ORDER:
                c = f(r[k], d)
                cells.append(f"**{c}**" if r[k] == best[k] else c)
            L.append(f"| {METHOD_LABELS[r['method']]} | " + " | ".join(cells) + " |")
        L.append("")
    sm = B["summary"]
    L += [f"**Summary.** Mean over 2×/4×/8×, the hybrid reduces RMSE by **{sm['hybrid_vs_bicubic_rmse_reduction_pct']:.1f} %** and "
          f"boundary RMSE by **{sm['hybrid_vs_bicubic_boundary_rmse_reduction_pct']:.1f} %** relative to bicubic interpolation. "
          f"Best RMSE per scale: " + ", ".join(f"{k}× → {METHOD_LABELS[v]}" for k, v in sm["best_rmse_method_per_scale"].items()) + ".", "",
          "Observations:", "",
          "* Among classical methods, guided filtering and joint bilateral upsampling beat plain interpolation, and the gap grows with the factor (8×).",
          "* DepthNet is the largest single improvement; the hybrid's measurement-consistency step adds a further, smaller gain in RMSE and boundary RMSE at every scale.",
          "* DepthNet has slightly lower MAE than the hybrid at 2×/4×: the residual correction re-introduces a little sensor noise in flat regions while fixing larger errors near edges.",
          "* Latency stays well under the 10 s target at this size on CPU; the hosted app caps outputs at 1.2 MP.", ""]
    L += [f"## 4. Ablation study ({A['scale']}×, {A['n_scenes']} test scenes)", "",
          "Each row removes (−) or adds (+) one component of the default hybrid.", "",
          "| Variant | RMSE (m) | MAE (m) | PSNR | SSIM | Edge F1 | Boundary RMSE (m) | Coverage |", "|---|---|---|---|---|---|---|---|"]
    for r in A["rows"]:
        L.append(f"| {r['variant']} | {f(r['RMSE'],4)} | {f(r['MAE'],4)} | {f(r['PSNR'],2)} | {f(r['SSIM'],4)} | {f(r['Edge F1'],4)} | {f(r['Boundary RMSE'],4)} | {f(r['Coverage'],3)} |")
    L += ["", "Findings (improvements and disadvantages):", "",
          "* **Deep learning** is the most important component: removing it more than doubles RMSE.",
          "* **RGB guidance** is almost as important: without it DepthNet cannot locate edges that fell between low-res samples.",
          "* **Residual (measurement-consistency) correction** gives a consistent gain in RMSE, boundary RMSE and Edge F1 for a small latency cost.",
          "* **Hole filling off** looks better on RMSE only because the hardest pixels are left empty (coverage < 1) — not a real improvement.",
          "* **Noise reduction** (wider residual filter) is roughly neutral at this noise level.",
          "* **RGB-JBU fusion** and **flying-pixel snapping** — part of our original design — *hurt* once DepthNet was trained: they move "
          "correct CNN edges towards RGB edges that are not depth edges (texture, shading, camouflage). They are kept as optional stages and are off by default.",
          "* Structure-edge gating made almost no difference *inside the fusion* because the fusion itself was the problem; the texture-copy index shows little texture leaking for any variant on these scenes.", ""]
    L += [f"## 5. Failure-case analysis ({F['scale']}×, {F['n_scenes_per_case']} scenes per case)", "",
          "| Case | Method | RMSE (m) | Boundary RMSE (m) | Edge F1 | Texture-copy idx |", "|---|---|---|---|---|---|"]
    for r in F["rows"]:
        L.append(f"| {r['case']} | {r['method']} | {f(r['RMSE'],4)} | {f(r['Boundary RMSE'],4)} | {f(r['Edge F1'],4)} | {f(r['Texture-copy idx'],4)} |")
    L += ["", "Visual sheets: `results/failure_cases/*.png` (RGB · Bicubic · JBU · DepthNet · Hybrid · GT · hybrid error).", "",
          "Honest discussion:", "",
          "* **Misaligned RGB/depth** is our clearest failure: DepthNet trusts the RGB edges and places depth boundaries 6 px off, ending up *worse than bicubic*. "
          "The hybrid's correction against the real measurements recovers part of the loss but still trails bicubic. Mitigation: check alignment (the Studio shows an RGB–depth edge-agreement score) or disable RGB guidance.",
          "* **Heavy noise:** DepthNet denoises well, but the hybrid's residual correction re-injects measurement noise, so the hybrid is worse than DepthNet alone here. Raising *noise reduction* widens the residual filter; an automatic noise estimate would be a next step.",
          "* **Very sparse (5 %) input:** all methods degrade strongly; learned methods remain best but boundaries are guessed from RGB and Edge F1 drops.",
          "* **Reflective surfaces:** the depth hole is filled plausibly, but the specular highlight's RGB edge leaks into depth (highest texture-copy index of all cases for DepthNet).",
          "* **Large missing regions:** filled smoothly; shapes inside big holes are interpolated, not recovered.",
          "* **Thin structures / strong boundaries / texture-heavy surfaces:** handled well by DepthNet and hybrid; poles thinner than the LR sampling step can still vanish completely at 8×.",
          "* **Synthetic-to-real gap:** all results are on procedural data. Real sensors add structured noise, multipath and calibration error that this benchmark does not contain.", ""]
    OUT.write_text("\n".join(L) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
